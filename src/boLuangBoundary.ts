export function isInsideBoLuang(lat: number, lng: number) {
  let inside = false;
  for (let i = 0, j = BO_LUANG_BOUNDARY.length - 1; i < BO_LUANG_BOUNDARY.length; j = i++) {
    const [yi, xi] = BO_LUANG_BOUNDARY[i];
    const [yj, xj] = BO_LUANG_BOUNDARY[j];
    const intersects =
      yi > lat !== yj > lat &&
      lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersects) inside = !inside;
  }
  return inside;
}
